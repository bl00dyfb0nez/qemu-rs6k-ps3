def be32(v: int) -> bytes:
    return struct.pack(">I", v & 0xFFFFFFFF)


def be16(v: int) -> bytes:
    return struct.pack(">H", v & 0xFFFF)


def u16(data: bytes, off: int) -> int:
    return struct.unpack_from(">H", data, off)[0]


def derive(seed: str, label: str, n: int) -> bytes:
    return hashlib.shake_256((seed + ":" + label).encode()).digest(n)


def parse_hex(value: str, n: int, what: str) -> bytes:
    raw = bytes.fromhex("".join(value.split()))
    if len(raw) != n:
        raise ValueError("%s must be %d bytes, got %d" % (what, n, len(raw)))
    return raw


def default_identity(seed: str, profile: dict) -> dict:
    """A valid-looking but deliberately synthetic PS3 identity."""
    model = profile["model"]
    if len(model) != 8:
        raise ValueError("profile model must be 8 bytes")
    board = int(profile.get("board_bits", 0)) & 0x3F
    rest = int.from_bytes(derive(seed, "idps-rest", 4), "big") & ((1 << 26) - 1)
    packed = (board << 26) | rest
    idps = model + packed.to_bytes(4, "big") + derive(seed, "idps-tail", 4)

    psid = b"PSID" + derive(seed, "psid", 12)
    openpsid = b"OPID" + derive(seed, "openpsid", 12)
    cid = bytes.fromhex("0fff") + derive(seed, "cid", 4)
    mac = b"\x02" + derive(seed, "mac", 5)
    nonce = derive(seed, "nonce", 12)
    ecid = derive(seed, "ecid", 16).hex().upper().encode("ascii")
    board_serial = ("%08d" % (int.from_bytes(derive(seed, "board", 4), "big") % 100000000))
    kiban = ("%012d" % (int.from_bytes(derive(seed, "kiban", 6), "big") % 10**12))
    ckp1 = derive(seed, "ckp1", 8)
    return {
        "idps": idps,
        "psid": psid,
        "openpsid": openpsid,
        "cid": cid,
        "mac": mac,
        "nonce": nonce,
        "ecid": ecid,
        "board": board_serial.encode("ascii"),
        "kiban": kiban.encode("ascii"),
        "ckp1": ckp1,
        "tail": bytes.fromhex("0012000b"),
    }


def section_keys(erk: bytes):
    if len(erk) != 48:
        raise ValueError("ERK must be 48 bytes")
    indiv = AES.new(erk[:32], AES.MODE_CBC, erk[32:48]).encrypt(INDIV_SEED)
    key32 = indiv[0x20:0x40]
    iv = indiv[0x10:0x20]
    keys = {
        0: AES.new(key32, AES.MODE_ECB).encrypt(SECTION_SEED_0),
        6: AES.new(key32, AES.MODE_ECB).encrypt(SECTION_SEED_6),
        10: AES.new(key32, AES.MODE_ECB).encrypt(SECTION_SEED_A),
    }
    return keys, iv


def section_plain(data: bytes, label: str) -> bytes:
    if len(data) != 16:
        raise ValueError("section identity must be 16 bytes")
    pt = bytearray(SECTION)
    pt[:16] = data
    marker = (label.encode("ascii") + b"\x00" * SECTION)[: SECTION - 16]
    pt[16:] = marker[: SECTION - 16]
    return bytes(pt)


def seal_section(key: bytes, iv: bytes, plain: bytes) -> bytes:
    mac = CMAC.new(key, ciphermod=AES)
    mac.update(plain[:CMAC_LEN])
    buf = bytearray(plain)
    buf[CMAC_LEN:CMAC_LEN + 16] = mac.digest()
    return AES.new(key, AES.MODE_CBC, iv).encrypt(bytes(buf))


def open_section(key: bytes, iv: bytes, cipher: bytes) -> bytes:
    plain = AES.new(key, AES.MODE_CBC, iv).decrypt(cipher)
    mac = CMAC.new(key, ciphermod=AES)
    mac.update(plain[:CMAC_LEN])
    if mac.digest() != plain[CMAC_LEN:CMAC_LEN + 16]:
        raise ValueError("section CMAC does not verify")
    return plain


def build_eid(ident: dict, erk: bytes) -> bytes:
    keys, iv = section_keys(erk)
    p0 = section_plain(ident["idps"], "synthetic EID0 section 0 IDPS")
    p6 = section_plain(ident["psid"], "synthetic EID0 section 6 PSID")
    pa = section_plain(ident["openpsid"], "synthetic EID0 section A OpenPSID")
    c0 = seal_section(keys[0], iv, p0)
    c6 = seal_section(keys[6], iv, p6)
    ca = seal_section(keys[10], iv, pa)

    eid0 = bytearray(b"\xff" * EID0_SIZE)
    eid0[:16] = ident["idps"]
    eid0[16:20] = ident["tail"]
    eid0[20:32] = ident["nonce"]
    eid0[0x20:0x20 + SECTION] = c0
    eid0[SECTION_6:SECTION_6 + SECTION] = c6
    eid0[SECTION_A:SECTION_A + SECTION] = ca

    entries = [
        (EID0_OFF, EID0_SIZE, 0),
        (0x08D0, 0x02A0, 1),
        (0x0B70, 0x0730, 2),
        (0x12A0, 0x0100, 3),
        (0x13A0, 0x0030, 4),
        (0x13D0, 0x0A00, 5),
    ]
    eid = bytearray(b"\xff" * EID_SIZE)
    eid[0:8] = bytes.fromhex("0000000600001dd0")
    eid[0x08:0x10] = b"\x00" * 8
    for i, (off, size, idx) in enumerate(entries):
        struct.pack_into(">IIQ", eid, 0x10 + i * 0x10, off, size, idx)
    eid[EID0_OFF:EID0_OFF + EID0_SIZE] = eid0
    return bytes(eid)


def build_cisd(ident: dict, rev: dict) -> bytes:
    c = bytearray(b"\xff" * CISD_SIZE)
    struct.pack_into(">II", c, 0, 3, 0x270)
    c[0x08:0x10] = b"\x00" * 8
    entries = [(0x040, 0x020, 0), (0x060, 0x200, 1), (0x260, 0x010, 2)]
    for i, (off, size, idx) in enumerate(entries):
        struct.pack_into(">IIII", c, 0x10 + i * 0x10, off, size, 0, idx)

    # cISD0: MAC address, then 0xFF.
    c[0x40:0x46] = ident["mac"]
    c[0x46:0x60] = b"\xff" * (0x20 - 6)

    # cISD1: IDLog.  Offsets follow docs/cisd.txt.
    log = bytearray(b"\xff" * CISD1_SIZE)
    log[0x00:0x04] = b"\x7fIDL"
    log[0x04:0x0A] = rev["idlog_semistatic"]  # version 2, avail 0x60, unknown 0x0100
    log[0x0A:0x10] = ident["cid"]
    log[0x10:0x30] = ident["ecid"][:32].ljust(32, b"0")
    log[0x30:0x38] = ident["board"][:8].ljust(8, b"0")
    log[0x38:0x44] = ident["kiban"][:12].ljust(12, b"0")
    struct.pack_into(">HHHH", log, 0x44,
                     rev["bootldr"], rev["osupdater"], rev["boarddiag"],
                     rev.get("configboot", 0x0001))
    log[0x4C:0x50] = b"\xff" * 4
    struct.pack_into(">HHHH", log, 0x50,
                     rev["ckp2"], rev["libboot"], rev["unk54"], rev["unk56"])
    log[0x58:0x60] = ident["ckp1"]
    c[CISD1_OFF:CISD1_OFF + CISD1_SIZE] = log

    # cISD2: WLAN data, then eight zero bytes.
    c[0x260:0x268] = rev["wlan"]
    c[0x268:0x270] = b"\x00" * 8
    return bytes(c)


def build_nor(eid: bytes, cisd: bytes) -> bytes:
    """A 16 MiB test image with just enough TOC for cisdinfo.py.

    The TOC shape is the one cisdinfo.toc_entries() accepts: a zero u32 at
    +0, the count at +4, and 0x30-byte entries from +0x10, offsets relative
    to 0x400.  Only eEID and cISD are present; everything else is 0xFF.
    """
    img = bytearray(b"\xff" * 0x1000000)
    struct.pack_into(">II", img, 0x400, 0, 2)
    for i, (name, off, size) in enumerate(
            (("eEID", 0x2F000, 0x10000), ("cISD", 0x3F000, 0x800))):
        p = 0x410 + i * 0x30
        struct.pack_into(">QQ", img, p, off - 0x400, size)
        field = bytearray(0x20)
        field[:len(name)] = name.encode("ascii")
        img[p + 0x10:p + 0x30] = field
    img[0x2F000:0x3F000] = eid
    img[0x3F000:0x3F800] = cisd
    return bytes(img)


def validate_eid(eid: bytes, ident: dict, erk: bytes) -> list[str]:
    errors = []
    if len(eid) != EID_SIZE:
        return ["eEID size is %d, expected %d" % (len(eid), EID_SIZE)]
    if eid[0:8] != bytes.fromhex("0000000600001dd0"):
        errors.append("eEID header is not 6 entries / 0x1DD0")
    for i in range(6):
        off, size, idx = struct.unpack_from(">IIQ", eid, 0x10 + i * 0x10)
        if off + size > EID_SIZE or idx != i:
            errors.append("eEID table entry %d is invalid" % i)
    keys, iv = section_keys(erk)
    for num, off, seed_data, name in (
        (0, 0x20, ident["idps"], "IDPS"),
        (6, SECTION_6, ident["psid"], "PSID"),
        (10, SECTION_A, ident["openpsid"], "OpenPSID"),
    ):
        eid0 = eid[EID0_OFF:EID0_OFF + EID0_SIZE]
        try:
            plain = open_section(keys[num], iv, eid0[off:off + SECTION])
        except ValueError as exc:
            errors.append("section %d %s: %s" % (num, name, exc))
            continue
        if plain[:16] != seed_data:
            errors.append("section %d %s does not carry the chosen value" % (num, name))
    return errors


def validate_cisd(cisd: bytes, ident: dict) -> list[str]:
    errors = []
    if len(cisd) != CISD_SIZE:
        return ["cISD size is %d, expected %d" % (len(cisd), CISD_SIZE)]
    count, total = struct.unpack_from(">II", cisd, 0)
    if count != 3 or total != 0x270:
        errors.append("cISD header is not 3 entries / 0x270")
    for i in range(count):
        off, size, res, idx = struct.unpack_from(">IIII", cisd, 0x10 + i * 0x10)
        if off + size > CISD_SIZE or res != 0 or idx != i:
            errors.append("cISD table entry %d is invalid" % i)
    if cisd[0x40:0x46] != ident["mac"]:
        errors.append("cISD0 MAC does not match")
    if cisd[0x60:0x64] != b"\x7fIDL":
        errors.append("cISD1 IDLog magic is missing")
    if cisd[0x6A:0x70] != ident["cid"]:
        errors.append("cISD1 CID does not match")
    return errors


def read_profile_from_dump(path: str, board: str | None,
                           minver: str | None) -> tuple[dict, dict]:
    """Read only model/version fields from a dump; never its identity.

    The IDPS is plaintext in the EID0 header: bytes 0..7 are the model prefix
    and bits 10..15 of bytes 8..9 are the board field.  The rest of the IDPS,
    the nonce, and every cISD identity field are deliberately not read into
    the output profile.
    """
    d = open(path, "rb").read()
    if len(d) < 0x1000000:
        raise ValueError("profile source is shorter than 16 MiB")
    eid = d[0x2F000:0x30000]
    if eid[0:8] != bytes.fromhex("0000000600001dd0"):
        raise ValueError("profile source has no 6-entry eEID header")
    eid0_off = eid0_size = None
    for i in range(6):
        off, size, idx = struct.unpack_from(">IIQ", eid, 0x10 + i * 0x10)
        if idx == 0:
            eid0_off, eid0_size = off, size
            break
    if eid0_off is None or eid0_size < 0x20 or eid0_off + 0x20 > len(eid):
        raise ValueError("profile source has no EID0 entry")
    idps = eid[eid0_off:eid0_off + 16]
    model = idps[:8]
    board_bits = (int.from_bytes(idps[8:10], "big") >> 10) & 0x3F

    cisd = d[0x3F000:0x3F800]
    count, total = struct.unpack_from(">II", cisd, 0)
    if count != 3 or total != 0x270:
        raise ValueError("profile source has no 3-entry cISD")
    log = cisd[CISD1_OFF:CISD1_OFF + CISD1_SIZE]
    if log[0:4] != b"\x7fIDL":
        raise ValueError("profile source cISD1 has no IDLog magic")
    rev = {
        "idlog_semistatic": log[0x04:0x0A],
        "bootldr": u16(log, 0x44),
        "osupdater": u16(log, 0x46),
        "boarddiag": u16(log, 0x48),
        "configboot": u16(log, 0x4A),
        "ckp2": u16(log, 0x50),
        "libboot": u16(log, 0x52),
        "unk54": u16(log, 0x54),
        "unk56": u16(log, 0x56),
        "wlan": cisd[0x260:0x268],
    }
    profile = {
        "name": "custom",
        "board": board or "dump-derived board",
        "model": model,
        "board_bits": board_bits,
        "minver": minver or "unknown",
        "source": "dump-derived profile",
    }
    return profile, rev


def make_manifest(outdir: str, ident: dict, erk: bytes, profile: dict,
                  files: dict, partial: bool) -> dict:
    return {
        "note": "synthetic test fixture; not a console key and not bootable retail",
        "usage": ("keep eEID.bin/cISD.bin separate from the dump; pair with a "
                  "dump of the same board/minver for emulation; do not flash"),
        "partial_match": partial,
        "profile": {
            "name": profile["name"],
            "board": profile["board"],
            "minver": profile["minver"],
            "source": profile["source"],
            "model": profile["model"].hex(),
            "board_bits": profile["board_bits"],
            "preserved": PRESERVED_FIELDS,
            "spoofed": SPOOFED_FIELDS,
        },
        "seed": None,
        "erk_file": os.path.join(outdir, "erk.bin"),
        "erk_sha256": hashlib.sha256(erk).hexdigest(),
        "identity": {k: v.hex() for k, v in ident.items() if isinstance(v, bytes)},
        "revisions": files,
    }



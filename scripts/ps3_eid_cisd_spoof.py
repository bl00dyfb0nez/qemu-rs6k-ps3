#!/usr/bin/env python3
"""ps3_eid_cisd_spoof.py - synthetic eEID + cISD fixtures for PS3 tool testing.

This builds a 64 KiB eEID and a 2 KiB cISD from a chosen synthetic identity:

  EID0 section 0   IDPS
  EID0 section 6   PSID
  EID0 section A   OpenPSID
  cISD0            MAC address
  cISD1            CID, eCID, board ID, kiban ID, version fields
  cISD2            WLAN data

The eEID's sealed sections are encrypted with the published chain:

  indiv       = AES-256-CBC(erk[0:32], iv=erk[32:48], individuals_seed)
  section key = AES-256-ECB(indiv[0x20:0x40], section_seed)
  ciphertext  = AES-128-CBC(section key, iv=indiv[0x10:0x20], plaintext)
  cmac        = AES-CMAC(section key) over plaintext[0:0xA8]

The ERK is a fixture generated by this tool.  It is NOT a console key, and an
eEID sealed with it will not authenticate on retail hardware.  Use it only with
tools/emulators that are given the same fixture ERK.

Spoofing model
--------------
A built-in profile supplies the public model prefix (company/product/
sub-product) and the 6-bit board field.  A dump-derived profile
(--profile-from) takes only those model fields and the cISD version block from
the dump.  It never copies the donor's IDPS rest, PSID, OpenPSID, CID, MAC,
eCID, board serial, kiban, CKP1 or nonce.  The result is therefore a deliberate
*partial* match: same board and firmware version family, different identity.

Keep the generated eEID/cISD separate from the dump.  Pair them with a dump
whose board/minver matches (for QEMU or offline tooling); do not merge the
synthetic identity bytes into the dump and do not flash them to hardware.

Example:

  python3 ps3_eid_cisd_spoof.py --outdir out --profile cech30xx --revision all
  python3 ps3_eid_cisd_spoof.py --outdir out --profile cech20xx --revision 4.84
  python3 ps3_eid_cisd_spoof.py --outdir out --profile-from /path/to/dump.bin

Outputs, per revision:

  <outdir>/<revision>/eEID.bin
  <outdir>/<revision>/cISD.bin
  <outdir>/erk.bin
  <outdir>/manifest.json
"""

